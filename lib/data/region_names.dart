/// languageCode가 'ko'면 한국어명, 그 외엔 영어명을 반환한다.
RegionInfo regionInfoFor(BodyView view, String regionId, String languageCode) {
  final map = view == BodyView.front ? frontRegionNames : backRegionNames;
  final entry = map[regionId];
  if (entry == null) return ('', '');
  return languageCode == 'ko' ? entry : (entry.$2, entry.$2);
}
